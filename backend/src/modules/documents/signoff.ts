/**
 * What the route engine tells the documents module as steps move: a submitted step gets its
 * sign-off record, a signature signs it, a return or a send-back closes it, and a send-back carries
 * each document forward (docs/documents-and-signing.md#step-sign-off-records, docs/workflow.md#failure-and-rework).
 * Everything runs in the action's own transaction. Nothing here imports the department module.
 */
export interface HookContext {
  deps: AppDeps;
  tx: Tx;
  log: ChangeLog;
  facts: ProjectFacts;
  /** A preview does the same work but writes no files, since it is rolled back. */
  preview: boolean;
  actor: Actor;
}

const SIGNOFF = 'STEP_SIGNOFF';

const signerOf = (actor: Actor): Signer => ({
  userId: actor.userId,
  name: actor.name,
  roleKey: actor.roleKey,
});

const SIGNOFF_BLOCKS: Block[] = [
  { type: 'title', text: 'Step sign-off record' },
  {
    type: 'rows',
    rows: [
      ['Project', '{project}'],
      ['Step', '{step}'],
      ['Iteration', '{iteration}'],
      ['Record number', '{number}'],
      ['Prepared by', '{prepared_by}'],
      ['Started on', '{started_on}'],
      ['Submitted on', '{submitted_on}'],
    ],
  },
  { type: 'heading', text: 'Outputs' },
  {
    type: 'loop',
    name: 'outputs',
    columns: [
      { header: 'Number', tag: 'number' },
      { header: 'Title', tag: 'title' },
      { header: 'Version', tag: 'version' },
      { header: 'Status', tag: 'status' },
      { header: 'Hash', tag: 'hash' },
    ],
  },
  { type: 'heading', text: 'Decisions' },
  {
    type: 'loop',
    name: 'decisions',
    columns: [
      { header: 'Decision', tag: 'name' },
      { header: 'Answer', tag: 'answer' },
    ],
  },
  { type: 'heading', text: 'Deviations' },
  { type: 'text', text: '{deviations}' },
];

const signoffDocx = () =>
  buildDocx(
    SIGNOFF_BLOCKS,
    'Generated by COAL · signatures are recorded in COAL against these hashes',
  );

async function signoffType(tx: Tx, orgId: string): Promise<TypeRow> {
  const type = await findTypeByCode(tx, orgId, SIGNOFF);
  if (!type) throw new AppError(500, 'INTERNAL', 'The step sign-off record type is missing.');
  return type;
}

/** The step's sign-off record, if there is one. */
async function findSignoff(
  tx: Tx,
  orgId: string,
  runId: string,
  stepKey: string,
  type: TypeRow,
): Promise<DocumentRow | null> {
  const rows = await documentsOfRun(tx, orgId, runId, stepKey);
  return rows.find((d) => d.documentTypeId === type.id) ?? null;
}

export interface SubmittedStep {
  step: StepDefinition;
  runStepId: string;
  iteration: number;
  openedAt: Date | null;
  /** Everyone who must sign, for steps where all of them must (the Board). */
  signers: string[];
  /** What the step decided: each decision's name and answer. */
  decisions: { name: string; answer: string }[];
}

const short = (hash: string | null) => (hash ? `${hash.slice(0, 12)}…` : '—');

/**
 * A step with a sign-off was submitted: makes its sign-off record, a new version each time, signed
 * Prepared by the person who submitted. Returns warnings for the preview.
 */
export async function onStepSubmitted(h: HookContext, s: SubmittedStep): Promise<string[]> {
  const { tx, deps, facts } = h;
  if (!s.step.signer) return [];
  const type = await signoffType(tx, facts.orgId);
  const warnings: string[] = [];

  // The step's outputs: each document's latest version, as it stands now.
  const docs = await documentsOfRun(tx, facts.orgId, facts.runId, s.step.key);
  const types = await findTypesById(
    tx,
    facts.orgId,
    docs.map((d) => d.documentTypeId),
  );
  // The record is read by the whole team, so it leaves out need-to-know documents (the budget
  // annex): they are signed on their own, and the people who may read them see them there.
  const outputs = docs.filter((d) => {
    const type = types.get(d.documentTypeId);
    return type?.kind !== 'record' && type?.sensitivity !== 'budget';
  });
  const versions = await versionsOf(
    tx,
    outputs.map((d) => d.id),
  );
  const rows = outputs.flatMap((d) => {
    const latest = versions.get(d.id)?.[0];
    if (!latest) return [];
    if (latest.status !== 'approved') {
      warnings.push(
        `${d.number} is not approved yet (version ${latest.versionNo}, ${latest.status.replace('_', ' ')}).`,
      );
    }
    return [
      {
        number: d.number,
        title: d.title,
        version: `${latest.versionNo}${latest.revLabel ? ` (rev ${latest.revLabel})` : ''}`,
        status: latest.status.replace('_', ' '),
        hash: short(latest.pdfSha256 ?? latest.contentSha256),
        content_sha256: latest.contentSha256,
        pdf_sha256: latest.pdfSha256 ?? '',
      },
    ];
  });

  let doc = await findSignoff(tx, facts.orgId, facts.runId, s.step.key, type);
  const created = !doc;
  if (!doc) {
    const count = await countDocumentsOfType(tx, facts.orgId, facts.runId, type.id);
    const [row] = await tx
      .insert(documents)
      .values({
        orgId: facts.orgId,
        runId: facts.runId,
        stepKey: s.step.key,
        documentTypeId: type.id,
        templateId: null,
        number: formatDocumentNumber(type.numberingPattern, {
          projectCode: facts.code,
          type: type.code,
          nn: count + 1,
        }),
        title: `Step ${s.step.key} sign-off: ${s.step.name}`,
        signaturePlan: type.signaturePlan,
        createdBy: h.actor.userId,
      })
      .returning();
    doc = row as DocumentRow;
  }

  const content: DocumentContent = {
    fields: {
      project: `${facts.code} · ${facts.name}`,
      step: `${s.step.key} · ${s.step.name}`,
      iteration: String(s.iteration),
      number: doc.number,
      prepared_by: h.actor.name,
      started_on: s.openedAt ? todayInIndia(s.openedAt) : '—',
      submitted_on: todayInIndia(),
      deviations: 'None recorded.',
      outputs: rows,
      decisions: s.decisions,
    },
    sections: {},
  };
  const contentSha256 = hashContent(content);

  let pdf: { fileId: string; sha256: string } | null = null;
  if (!h.preview) {
    let filled: Buffer;
    try {
      filled = fillDocx(signoffDocx(), content.fields);
    } catch (error) {
      if (error instanceof DocxError)
        throw new AppError(500, 'INTERNAL', 'The sign-off record could not be made.');
      throw error;
    }
    const latest = await latestVersionOf(tx, doc.id);
    const name = `${doc.number}-v${(latest?.versionNo ?? 0) + 1}`;
    const bytes = await deps.pdf.fromDocx(filled, `${name}.docx`);
    const file = await storeGeneratedFile(deps, tx, facts.orgId, {
      name: `${name}.pdf`,
      bytes,
      contentType: 'application/pdf',
      userId: h.actor.userId,
    });
    pdf = { fileId: file.id, sha256: file.sha256 as string };
  }

  const version = await insertVersion(tx, facts.orgId, {
    documentId: doc.id,
    runStepId: s.runStepId,
    iteration: s.iteration,
    content,
    contentSha256,
    pdf,
    searchText: searchTextOf(doc.title, content),
    note: '',
    createdBy: h.actor.userId,
    status: 'in_review',
  });

  const plan = planRows(
    doc.signaturePlan,
    { signer: s.step.signer, boardSigners: s.step.all_must_sign ? s.signers : [] },
    signerOf(h.actor),
  );
  const requests = await openRows(tx, facts.orgId, version.id, plan);
  const prepared = requests.find((r) => r.meaning === 'prepared') as RequestRow;
  await signRow(tx, facts.orgId, version, prepared, signerOf(h.actor));

  if (created) {
    h.log.audit({
      action: 'document.created',
      recordType: 'document',
      recordId: doc.id,
      after: { number: doc.number, title: doc.title, type: SIGNOFF, stepKey: s.step.key },
    });
  }
  h.log.audit({
    action: 'document.version_saved',
    recordType: 'document_version',
    recordId: version.id,
    after: {
      number: doc.number,
      versionNo: version.versionNo,
      contentSha256,
      pdfSha256: pdf?.sha256 ?? null,
    },
  });
  h.log.audit({
    action: 'signature.signed',
    recordType: 'document_version',
    recordId: version.id,
    after: { meaning: 'prepared', by: h.actor.name, contentSha256 },
  });
  h.log.event({
    type: 'document.submitted',
    projectId: facts.projectId,
    stepKey: s.step.key,
    payload: {
      documentId: doc.id,
      number: doc.number,
      versionNo: version.versionNo,
      kind: 'step_signoff',
    },
  });
  return warnings;
}

/** The step's latest sign-off version, if it is waiting for signatures. */
async function openSignoff(h: HookContext, stepKey: string) {
  const type = await signoffType(h.tx, h.facts.orgId);
  const doc = await findSignoff(h.tx, h.facts.orgId, h.facts.runId, stepKey, type);
  if (!doc) return null;
  const version = await latestVersionOf(h.tx, doc.id);
  if (!version || version.status !== 'in_review') return null;
  const requests = (await requestsOfVersions(h.tx, [version.id])).get(version.id) ?? [];
  return { doc, version, requests };
}

/**
 * A signer approved the step (alone, or as one of several): signs their row of the sign-off record.
 * Steps submitted before sign-off records existed have none, and are left as they were.
 */
export async function onStepSigned(
  h: HookContext,
  stepKey: string,
  by: { userId: string; name: string; roleKey: string },
): Promise<void> {
  const open = await openSignoff(h, stepKey);
  if (!open) return;
  const pending = open.requests.filter((r) => r.meaning === 'approved' && r.status === 'pending');
  const mine =
    pending.find((r) => r.assigneeId === by.userId) ?? pending.find((r) => !r.assigneeId);
  if (!mine) return;
  const { complete } = await signRow(h.tx, h.facts.orgId, open.version, mine, by);
  h.log.audit({
    action: 'signature.signed',
    recordType: 'document_version',
    recordId: open.version.id,
    after: {
      meaning: 'approved',
      by: by.name,
      number: open.doc.number,
      contentSha256: open.version.contentSha256,
      pdfSha256: open.version.pdfSha256,
    },
  });
  h.log.event({
    type: 'signature.signed',
    projectId: h.facts.projectId,
    stepKey,
    payload: { documentId: open.doc.id, number: open.doc.number, meaning: 'approved' },
  });
  if (complete)
    await approveVersion(h.tx, h.log, open.doc, open.version, stepKey, h.facts.projectId);
}

/** The signer returned the step: its sign-off record goes back to the authors with the comment. */
export async function onStepReturned(
  h: HookContext,
  stepKey: string,
  comment: string,
): Promise<void> {
  const open = await openSignoff(h, stepKey);
  if (!open) return;
  const pending = open.requests.find((r) => r.meaning === 'approved' && r.status === 'pending');
  await returnVersion(
    h.tx,
    h.log,
    open.doc,
    open.version,
    {
      request:
        pending && (!pending.assigneeId || pending.assigneeId === h.actor.userId) ? pending : null,
      by: signerOf(h.actor),
      comment,
    },
    stepKey,
    h.facts.projectId,
  );
}

/**
 * A send-back closed the step's iteration: anything waiting for signatures is returned, and each
 * document's latest version is copied into the new iteration as a new draft, so people revise
 * rather than start again.
 */
export async function onStepReset(
  h: HookContext,
  stepKey: string,
  next: { runStepId: string; iteration: number },
): Promise<void> {
  const { tx, facts } = h;
  const docs = await documentsOfRun(tx, facts.orgId, facts.runId, stepKey);
  const types = await findTypesById(
    tx,
    facts.orgId,
    docs.map((d) => d.documentTypeId),
  );
  const versions = await versionsOf(
    tx,
    docs.map((d) => d.id),
  );

  for (const doc of docs) {
    const latest = versions.get(doc.id)?.[0];
    if (!latest) continue;
    const isRecord = types.get(doc.documentTypeId)?.kind === 'record';
    if (latest.status === 'in_review') {
      await returnVersion(
        tx,
        h.log,
        doc,
        latest,
        { request: null, by: null, comment: 'The step was sent back.' },
        stepKey,
        facts.projectId,
      );
    }
    if (isRecord) continue;
    const copy = await insertVersion(tx, facts.orgId, {
      documentId: doc.id,
      runStepId: next.runStepId,
      iteration: next.iteration,
      content: latest.content,
      contentSha256: latest.contentSha256,
      fileId: latest.fileId,
      pdf:
        latest.pdfFileId && latest.pdfSha256
          ? { fileId: latest.pdfFileId, sha256: latest.pdfSha256 }
          : null,
      searchText: latest.searchText,
      note: 'Carried forward from the earlier iteration.',
      createdBy: h.actor.userId,
      carriedFromVersionId: latest.id,
    });
    h.log.audit({
      action: 'document.carried_forward',
      recordType: 'document_version',
      recordId: copy.id,
      after: {
        number: doc.number,
        versionNo: copy.versionNo,
        from: latest.versionNo,
        iteration: next.iteration,
      },
    });
    h.log.event({
      type: 'document.carried_forward',
      projectId: facts.projectId,
      stepKey,
      payload: { documentId: doc.id, number: doc.number, versionNo: copy.versionNo },
    });
  }
}

/** A decision is signed by the person who made it, with a hash of exactly what was decided. */
export async function signDecision(h: HookContext, decision: DecisionRow): Promise<void> {
  const contentSha256 = sha256(
    canonicalJson({
      id: decision.id,
      runId: decision.runId,
      stepKey: decision.stepKey,
      iteration: decision.iteration,
      decision: decision.decision,
      value: decision.value,
      reason: decision.reason,
      decidedBy: decision.decidedBy,
    }),
  );
  await insertSignature(h.tx, h.facts.orgId, {
    request: null,
    subject: { type: 'decision', id: decision.id, contentSha256, pdfSha256: null },
    signer: signerOf(h.actor),
    meaning: 'decision',
    decision: decision.value,
    reason: decision.reason,
  });
  h.log.audit({
    action: 'signature.signed',
    recordType: 'decision',
    recordId: decision.id,
    after: {
      meaning: 'decision',
      decision: decision.decision,
      value: decision.value,
      contentSha256,
    },
    reason: decision.reason,
  });
}
